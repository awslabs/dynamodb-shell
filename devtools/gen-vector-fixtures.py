# devtools/gen-vector-fixtures.py — deterministic seed generator for the live
# vector-search golden family (phase 4b, P4b-02).
#
# For each dimension D in the ladder it emits tests/golden/data/ddbsh-vec-<D>.sql
# containing a CREATE TABLE with a dim-D vector index (search key: category
# FILTER, PROJECTING ALL) plus ~50 rows of deterministic, well-SEPARATED vectors
# arranged in K clusters so the nearest-neighbour membership of a query aimed at
# cluster 0 is unambiguous.
#
# Fixture geometry (fully deterministic, so the recorded scores are stable and
# the top-K membership is exact — the index does exact search over this tiny
# set):
#   * K = min(5, D) clusters, POINTS_PER_CLUSTER points each.
#   * cluster c is centered at CENTER on coordinate c (all other coords 0).
#   * point j in cluster c adds j * STEP on coordinate (c + 1) % D.
#   * the query vector is CENTER on coordinate 0 (the cluster-0 center), so the
#     NEAREST POINTS_PER_CLUSTER are exactly cluster 0's members, at euclidean
#     distances 0, STEP, 2*STEP, ... (well under the ~CENTER*sqrt(2) gap to any
#     other cluster).
#
# The query itself lives in the family .txt (not here); this only seeds data.
# Rerun after changing the ladder/geometry, then re-record the goldens.

import os

LADDER = [2, 3, 4, 8, 16, 128, 768, 1536, 4096]
POINTS_PER_CLUSTER = 10
CENTER = 10.0
STEP = 0.1

HERE = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(HERE, "..", "tests", "golden", "data")

HEADER = (
    "-- Copyright 2026 ddbsh reimplementation contributors.\n"
    "-- SPDX-License-Identifier: Apache-2.0\n"
    "--\n"
    "-- GENERATED by devtools/gen-vector-fixtures.py -- do not edit by hand.\n"
    "-- Dimension {d}: {k} well-separated clusters x {ppc} points; the vector\n"
    "-- index is dim-{d}, euclidean, search key (category FILTER), PROJECTING ALL.\n"
)


def fmt(x: float) -> str:
    # Compact, deterministic decimal rendering (one place is enough for STEP).
    s = f"{x:.1f}"
    return s


def vector(d: int, coord: int, value: float, coord2: int, value2: float):
    v = [0.0] * d
    v[coord] = value
    if coord2 is not None:
        v[coord2] += value2
    return "[" + ", ".join(fmt(x) for x in v) + "]"


def gen(d: int) -> str:
    k = min(5, d)
    table = f"ddbsh_vec_{d}"
    out = [HEADER.format(d=d, k=k, ppc=POINTS_PER_CLUSTER)]
    out.append(
        f"create table {table} ( a number, category string ) "
        f"primary key ( a hash ) "
        f"vsi ( vidx on point dimensions {d} distance euclidean "
        f"search key ( category filter ) projecting all );\n"
    )
    a = 0
    for c in range(k):
        cat = f"c{c}"
        for j in range(POINTS_PER_CLUSTER):
            a += 1
            vec = vector(d, c, CENTER, (c + 1) % d, j * STEP)
            out.append(
                f'insert into {table} (a, category, point) '
                f'values ({a}, "{cat}", {vec});\n'
            )
    return "".join(out)


def nearest_to(d: int) -> str:
    # Query vector = cluster-0 center: CENTER on coord 0, zeros elsewhere.
    v = [0.0] * d
    v[0] = CENTER
    return "[" + ", ".join(fmt(x) for x in v) + "]"


FAMILY_HEADER = """# Copyright 2026 ddbsh reimplementation contributors.
# SPDX-License-Identifier: Apache-2.0
#
# vector.txt — LIVE real-DynamoDB goldens for vector search (phase 4b, P4b-02).
#
# GENERATED by devtools/gen-vector-fixtures.py -- do not edit by hand (the
# high-dimension NEAREST query vectors are machine-generated). Rerun the
# generator and re-record the goldens after changing the ladder/geometry.
#
# This closes the gap the human called out: the vector feature had ZERO live
# golden coverage (all prior vector tests used the offline FakeDDBClient). Each
# dimension in the ladder ({ladder}) seeds a real table with a dim-D vector
# index (euclidean, search key category FILTER, PROJECTING ALL) from
# ${{DATA}}/ddbsh-vec-<D>.sql (K clusters x {ppc} well-separated points), runs a
# NEAREST query aimed at cluster 0, and asserts the returned rows.
#
# These goldens are AUTHORED (SearchVectors postdates the original ddbsh, so
# there is no oracle) and human-audited before merge (D-2i-5 / P4b-02).
#
# Matching: NEAREST rows carry a per-row ` score <n>` and come back in
# similarity order, so every data query uses -s (LC_ALL=C sort) + a sorted
# byte-exact .exp. The fixtures are well separated and the index does exact
# search over the tiny set, so the trim_double-formatted scores are stable
# run-to-run (verified live), and the top-K membership is unambiguous (the
# query targets cluster 0; its {ppc} members are the {ppc} nearest). No harness
# score-tolerance mode is needed for these fixtures.
#
# B2 (vector not returned): SearchVectors returns each match's projected
# NON-vector attributes plus the score; it does NOT echo the stored vector. The
# NEAREST goldens below therefore show `{{a: N, category: cK}} score <n>` with
# NO `point` attribute even though the index is PROJECTING ALL and the query is
# SELECT * -- this is the live, service-side behavior the README/HELP document.
#
# ${{RD}} is the golden results dir; ${{DATA}} is the seed dir.
#
# WARNING: creates/loads/drops REAL DynamoDB tables (ddbsh_vec_<D>) on each run
# (us-east-1). Each CREATE waits for the vector index to be ACTIVE (~30s).
# Self-cleaning (each dimension drops its table before the next). The live
# vector families require an AWS SDK with SearchVectors (>= 1.11.916); in a CI
# version-set without it they will not run (HG-2, human-gated).
"""


def gen_family() -> str:
    out = [FAMILY_HEADER.format(
        ladder=", ".join(str(d) for d in LADDER),
        ppc=POINTS_PER_CLUSTER)]
    out.append("\n")
    # Backend-free EXPLAIN goldens for the B1 ALTER-create-VSI forms (no search
    # key, with search key). Deterministic request serialization, no table.
    out.append(
        "# --- backend-free EXPLAIN of ALTER CREATE VSI (B1: optional/empty "
        "attribute parens) ---\n")
    out.append(
        'add_test(NAME ivec-alter-explain-nokey COMMAND ddbshtest -q '
        '-T ${RD}/ivec-alter-explain-nokey.exp '
        '-c "explain alter table foo create vsi vidx on point dimensions 3 '
        'distance euclidean projecting all;")\n')
    out.append(
        'add_test(NAME ivec-alter-explain-key COMMAND ddbshtest -q '
        '-T ${RD}/ivec-alter-explain-key.exp '
        '-c "explain alter table foo ( category string ) create vector index '
        'vidx on point dimensions 1536 distance cosine search key '
        '( category filter ) projecting all;")\n\n')

    for d in LADDER:
        table = f"ddbsh_vec_{d}"
        to = nearest_to(d)
        out.append(f"# --- dimension {d} ---\n")
        out.append(
            f'add_test(NAME ivec-{d}-setup COMMAND ddbshtest '
            f'-f ${{DATA}}/ddbsh-vec-{d}.sql)\n')
        out.append(
            f'add_test(NAME ivec-{d}-nearest COMMAND ddbshtest -q -s '
            f'-T ${{RD}}/ivec-{d}-nearest.exp '
            f'-c "select * from {table}.vidx nearest {POINTS_PER_CLUSTER} '
            f'to {to};")\n')
        if d == 3:
            # Representative extras on the dim-3 table: deterministic EXPLAIN of
            # the SearchVectors plan, and a filtered NEAREST (search-key FILTER).
            out.append(
                f'add_test(NAME ivec-{d}-explain COMMAND ddbshtest -q '
                f'-T ${{RD}}/ivec-{d}-explain.exp '
                f'-c "explain select * from {table}.vidx nearest '
                f'{POINTS_PER_CLUSTER} to {to};")\n')
            out.append(
                f'add_test(NAME ivec-{d}-filtered COMMAND ddbshtest -q -s '
                f'-T ${{RD}}/ivec-{d}-filtered.exp '
                f'-c "select * from {table}.vidx where category = \\"c0\\" '
                f'nearest 5 to {to};")\n')
        out.append(
            f'add_test(NAME ivec-{d}-drop COMMAND ddbshtest '
            f'-c "drop table {table};")\n\n')
    return "".join(out)


def main():
    os.makedirs(DATA_DIR, exist_ok=True)
    for d in LADDER:
        path = os.path.join(DATA_DIR, f"ddbsh-vec-{d}.sql")
        with open(path, "w") as f:
            f.write(gen(d))
        print(f"wrote {os.path.relpath(path)}")
    fam = os.path.join(HERE, "..", "tests", "golden", "families", "vector.txt")
    with open(fam, "w") as f:
        f.write(gen_family())
    print(f"wrote {os.path.relpath(fam)}")


if __name__ == "__main__":
    main()
